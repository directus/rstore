import { expect, test } from '@playwright/test'
import { callDevtools, createInspectorPanel, selectInspectorStore } from './devtoolsDriver'

test.beforeEach(async ({ page }) => {
  await page.goto('/test/browser/fixtures/index.html')
  await callDevtools(page, 'initialize', { rich: true, readOnly: true })
})

test('confirmed cache and history clears affect selected store while preserving another store and remote data', async ({ page }) => {
  const frame = await createInspectorPanel(page)
  const otherCache = await callDevtools(page, 'cacheRows', 'vue')
  const remoteRows = await callDevtools(page, 'backendRows', 'core')
  await frame.getByRole('button', { name: 'Cache', exact: true }).click()
  await frame.getByRole('button', { name: 'Clear cache', exact: true }).click()
  await expect(frame.getByRole('button', { name: 'Submit', exact: true })).toBeDisabled()
  await frame.getByRole('checkbox', { name: 'Confirm clear-cache', exact: true }).check()
  await frame.getByRole('button', { name: 'Submit', exact: true }).click()
  await expect(frame.getByText('No cached items', { exact: true })).toBeVisible()
  expect(await callDevtools(page, 'cacheRows', 'core')).toEqual([])
  expect(await callDevtools(page, 'cacheRows', 'vue')).toEqual(otherCache)
  expect(await callDevtools(page, 'backendRows', 'core')).toEqual(remoteRows)
  await frame.getByRole('button', { name: 'History', exact: true }).click()
  await expect(frame.getByText(/Fixture fetch failed/).first()).toBeVisible()
  await frame.getByRole('button', { name: 'Clear history', exact: true }).click()
  await frame.getByRole('checkbox', { name: 'Confirm clear-history', exact: true }).check()
  await frame.getByRole('button', { name: 'Submit', exact: true }).click()
  await expect(frame.getByText('No history', { exact: true })).toBeVisible()
  await expect(frame.getByText(/Fixture fetch failed/)).toHaveCount(0)
})
test.afterEach(async ({ page }) => {
  await callDevtools(page, 'dispose')
})

test('JSON collection CRUD changes actual remote rows and leaves other store intact', async ({ page }) => {
  const frame = await createInspectorPanel(page)
  const todos = frame.locator('article').filter({ has: frame.getByRole('heading', { name: 'todos', exact: true }) })
  await todos.getByRole('button', { name: 'Create item', exact: true }).click()
  await frame.getByRole('textbox', { name: 'JSON item', exact: true }).fill('{"id":"created","title":"Created through inspector"}')
  await frame.getByRole('button', { name: 'Submit', exact: true }).click()
  await expect(frame.getByRole('dialog')).not.toBeVisible()
  await expect.poll(async () => await callDevtools(page, 'backendRows', 'core')).toContainEqual({ id: 'created', title: 'Created through inspector' })
  await expect.poll(async () => await callDevtools(page, 'backendRows', 'vue')).not.toContainEqual({ id: 'created', title: 'Created through inspector' })

  await todos.getByRole('button', { name: 'Update item', exact: true }).click()
  await frame.getByRole('textbox', { name: 'Item key', exact: true }).fill('created')
  await frame.getByRole('textbox', { name: 'JSON item', exact: true }).fill('{"title":"Updated through inspector"}')
  await frame.getByRole('button', { name: 'Submit', exact: true }).click()
  await expect(frame.getByRole('dialog')).not.toBeVisible()
  await expect.poll(async () => await callDevtools(page, 'backendRows', 'core')).toContainEqual({ id: 'created', title: 'Updated through inspector' })

  await todos.getByRole('button', { name: 'Delete item', exact: true }).click()
  await frame.getByRole('textbox', { name: 'Item key', exact: true }).fill('created')
  await expect(frame.getByRole('button', { name: 'Submit', exact: true })).toBeDisabled()
  await frame.getByRole('checkbox', { name: 'Confirm delete-item', exact: true }).check()
  await frame.getByRole('button', { name: 'Submit', exact: true }).click()
  await expect(frame.getByRole('dialog')).not.toBeVisible()
  await expect.poll(async () => (await callDevtools(page, 'backendRows', 'core')).some((row: any) => row.id === 'created')).toBe(false)
  await expect.poll(async () => (await callDevtools(page, 'backendRows', 'vue')).some((row: any) => row.id === 'vue')).toBe(true)
})

test('cache actions preserve typed zero address and read-only target disables writes', async ({ page }) => {
  const frame = await createInspectorPanel(page)
  await frame.getByRole('button', { name: 'Cache', exact: true }).click()
  await frame.getByRole('button', { name: 'Write item', exact: true }).click()
  await frame.getByRole('textbox', { name: 'JSON item', exact: true }).fill('{"id":0,"title":"Zero key"}')
  await frame.getByRole('button', { name: 'Submit', exact: true }).click()
  await expect(frame.getByText('number: 0', { exact: true })).toBeVisible()
  await expect.poll(async () => await callDevtools(page, 'cacheRows', 'core')).toContainEqual({ id: 0, title: 'Zero key' })
  const row = frame.locator('article').filter({ hasText: 'number: 0' })
  await row.getByRole('button', { name: 'Delete cached item', exact: true }).click()
  await frame.getByRole('checkbox', { name: 'Confirm delete-cache-item', exact: true }).check()
  await frame.getByRole('button', { name: 'Submit', exact: true }).click()
  await expect(frame.getByText('number: 0', { exact: true })).toHaveCount(0)
  await expect.poll(async () => (await callDevtools(page, 'cacheRows', 'core')).some((item: any) => item.id === 0)).toBe(false)
  await selectInspectorStore(frame, 'readonly')
  await expect(frame.getByRole('button', { name: 'Write item', exact: true })).toBeDisabled()
  await expect(frame.getByRole('button', { name: 'Clear cache', exact: true })).toBeDisabled()
  await selectInspectorStore(frame, 'vue')
  await expect(frame.getByText('"vue row"', { exact: true })).toBeVisible()
})
